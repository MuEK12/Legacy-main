-----------------------------------------------------------------------------------------------------------------------------------------
-- REFRESHTHEME
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand("refreshtheme",function()
	SendNUIMessage({ Action = "RefreshTheme" })
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- HUD:MENU
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("hud:Menu")
AddEventHandler("hud:Menu",function()
	if not LocalPlayer.state.Active or LocalPlayer.state.Buttons or LocalPlayer.state.Handcuff then
		return
	end

	SetNuiFocus(true,true)
	SendNUIMessage({ Action = "Settings", Payload = true })
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- HUDSETTINGS
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand("hudsettings",function()
	SetNuiFocus(true,true)
	SendNUIMessage({ Action = "Settings", Payload = true })
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- HUD:SETTINGS
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("hud:Settings")
AddEventHandler("hud:Settings",function(State)
	SendNUIMessage({ Action = "Settings", Payload = State })
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- SETTINGSCLOSE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("SettingsClose",function(Data,Callback)
	SetNuiFocus(false,false)

	Callback("Ok")
end)