-----------------------------------------------------------------------------------------------------------------------------------------
-- SOUNDEXISTS
-----------------------------------------------------------------------------------------------------------------------------------------
function soundExists(name_)
    if soundInfo[name_] == nil then
        return false
    end
    return true
end

exports('soundExists', soundExists)

